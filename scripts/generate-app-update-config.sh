#!/usr/bin/env bash
# Generate apps/macos/DockBridge/Generated/AppUpdateReleaseConfig.swift from
# config/release.toml so update verification flags and signing identifiers stay
# in sync automatically at build time and in CI (issue #403).
#
# Usage:
#   scripts/generate-app-update-config.sh [--check] [--out <path>]
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
READER="${ROOT}/scripts/release-config.sh"
OUT_PATH="${ROOT}/apps/macos/DockBridge/Generated/AppUpdateReleaseConfig.swift"
CHECK_ONLY=false

usage() {
  echo "Usage: bash $0 [--check] [--out <path>]" >&2
  exit 1
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --check)
      [[ "$CHECK_ONLY" == false ]] || usage
      CHECK_ONLY=true
      shift
      ;;
    --out)
      [[ $# -ge 2 && -n "$2" ]] || usage
      OUT_PATH="$2"
      shift 2
      ;;
    *)
      usage
      ;;
  esac
done

GITHUB_REPO="$(bash "$READER" github_repo)"
APP_NAME="$(bash "$READER" app_name)"
BUNDLE_IDENTIFIER="$(bash "$READER" bundle_identifier)"
TEAM_ID="$(bash "$READER" --allow-empty team_id)"
CERT_FINGERPRINT="$(bash "$READER" --allow-empty signing_certificate_fingerprint_sha256)"
REQUIRE_SIGNED="$(bash "$READER" --bool require_signed_updates)"
REQUIRE_NOTARIZED="$(bash "$READER" --bool require_notarized_updates)"

if [[ ! "$GITHUB_REPO" =~ ^[A-Za-z0-9._-]+/[A-Za-z0-9._-]+$ ]]; then
  echo "error: invalid github_repo in config/release.toml: ${GITHUB_REPO}" >&2
  exit 1
fi
if [[ ! "$APP_NAME" =~ ^[A-Za-z0-9._\ -]+$ ]]; then
  echo "error: invalid app_name in config/release.toml: ${APP_NAME}" >&2
  exit 1
fi
if [[ ! "$BUNDLE_IDENTIFIER" =~ ^[A-Za-z0-9.-]+$ ]]; then
  echo "error: invalid bundle_identifier in config/release.toml: ${BUNDLE_IDENTIFIER}" >&2
  exit 1
fi
if [[ -n "$TEAM_ID" && ! "$TEAM_ID" =~ ^[A-Za-z0-9]+$ ]]; then
  echo "error: invalid team_id in config/release.toml: ${TEAM_ID}" >&2
  exit 1
fi
if [[ -n "$CERT_FINGERPRINT" && ! "$CERT_FINGERPRINT" =~ ^[0-9a-fA-F:]+$ ]]; then
  echo "error: invalid signing_certificate_fingerprint_sha256 in config/release.toml: ${CERT_FINGERPRINT}" >&2
  exit 1
fi

TMP_FILE=""
cleanup() {
  if [[ -n "$TMP_FILE" ]]; then
    rm -f "$TMP_FILE"
  fi
}
trap cleanup EXIT

OUT_DIR="$(dirname "$OUT_PATH")"
if [[ "$CHECK_ONLY" == true ]]; then
  TMP_FILE="$(mktemp)"
else
  mkdir -p "$OUT_DIR"
  TMP_FILE="$(mktemp "${OUT_DIR}/.AppUpdateReleaseConfig.XXXXXX")"
fi

cat > "$TMP_FILE" <<EOF
// Generated by scripts/generate-app-update-config.sh from config/release.toml.
// Do not edit manually; update config/release.toml and run
// ./scripts/generate-app-update-config.sh instead.

enum AppUpdateReleaseConfig {
    static let githubRepo = "${GITHUB_REPO}"
    static let appName = "${APP_NAME}"
    static let bundleIdentifier = "${BUNDLE_IDENTIFIER}"
    static let expectedTeamIdentifier = "${TEAM_ID}"
    static let signingCertificateFingerprintSHA256 = "${CERT_FINGERPRINT}"
    static let requireSignedUpdates = ${REQUIRE_SIGNED}
    static let requireNotarizedUpdates = ${REQUIRE_NOTARIZED}
}
EOF

if [[ "$CHECK_ONLY" == true ]]; then
  if [[ ! -f "$OUT_PATH" ]] || ! cmp -s "$TMP_FILE" "$OUT_PATH"; then
    echo "::error::${OUT_PATH} is out of date with config/release.toml. Run ./scripts/generate-app-update-config.sh and commit the result." >&2
    exit 1
  fi
  exit 0
fi

# Preserve mtime when content is unchanged so Xcode skips redundant recompiles.
if [[ -f "$OUT_PATH" ]] && cmp -s "$TMP_FILE" "$OUT_PATH"; then
  exit 0
fi

mv "$TMP_FILE" "$OUT_PATH"
TMP_FILE=""
